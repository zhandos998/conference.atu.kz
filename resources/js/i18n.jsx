const I18nContext = createContext(null);

const normalizeLanguage = (value) => (
  languages.some((language) => language.code === value) ? value : 'ru'
);

const getStoredLanguage = () => {
  if (typeof window === 'undefined') {
    return 'ru';
  }

  return normalizeLanguage(localStorage.getItem(STORAGE_KEY));
};

const readTranslation = (language, key) => translations[language]?.[key] ?? translations.ru[key] ?? key;

const interpolate = (template, params = {}) => template.replace(/\{(\w+)\}/g, (_, key) => (
  params[key] ?? `{${key}}`
));

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(getStoredLanguage);

  const setLanguage = (nextLanguage) => {
    const normalized = normalizeLanguage(nextLanguage);
    setLanguageState(normalized);
    localStorage.setItem(STORAGE_KEY, normalized);
  };

  useEffect(() => {
    const htmlLang = languages.find((item) => item.code === language)?.htmlLang ?? 'ru';
    document.documentElement.lang = htmlLang;
  }, [language]);

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key, params) => interpolate(readTranslation(language, key), params),
  }), [language]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);

  if (!context) {
    throw new Error('useI18n must be used inside LanguageProvider');
  }

  return context;
}

export function LanguageSwitcher({ className }) {
  const { language, setLanguage, t } = useI18n();

  return (
    <div className={className} aria-label={t('common.languageLabel')}>
      {languages.map((item) => (
        <button
          key={item.code}
          className={item.code === language ? 'is-active' : ''}
          type="button"
          onClick={() => setLanguage(item.code)}
        >
          {item.label}
        </button>
      ))}
    </div>
  );
}

export function getDirectionLabel(value, t) {
  const option = directionOptions.find((item) => item.value === value);

  return option ? t(`directions.${option.key}`) : value;
}

export function formatDateTime(value, language) {
  if (!value) {
    return '-';
  }

  const locale = language === 'kz' ? 'kk-KZ' : (language === 'en' ? 'en-US' : 'ru-RU');

  return new Date(value).toLocaleString(locale);
}
